// Старі 44 модулі (рівні A-I, levels.js) видалені навмисно - Академія
// переходить на нову структуру за напрямками дизайну з directions.js (Web
// Design, UI Design, Game Design тощо, показані на Головній). Нові модулі
// додаються сюди пізніше, згруповані по тому самому полю level, але зі
// значеннями slug-ів напрямків замість літер A-I - до того часу Академія
// просто порожня, а не показує застарілий контент.

export const MODULES = []

export function getModule(id) {
  return MODULES.find((m) => m.id === Number(id))
}
