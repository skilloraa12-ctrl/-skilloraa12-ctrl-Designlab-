// Розпізнавання НАМІРУ питання (а не лише пошук по тексту уроку).
// Досі mentorMatch.js вмів відповідати тільки на "питання про зміст уроку"
// (шукав збіг слів у теорії/принципах/помилках). Але учні питають набагато
// ширше: "я не зрозуміла завдання", "що далі", "дай підказку", "у мене не
// виходить" — це не питання ПРО зміст, а питання ПРО те, що з учнем зараз
// відбувається. Це все ще НЕ штучний інтелект: жодної мовної моделі, жодного
// API. Це нормалізація тексту + зіставлення з наперед заданими зразками
// формулювань (fuzzy: через токени й підрядки, а не лише дослівний збіг) —
// тобто "семантика" в межах наперед відомого списку намірів, а не вільне
// розуміння довільного тексту.
//
// Кожен намір (intent) має:
//   id        — ключ, за яким mentorTemplates.js будує відповідь
//   handler   — яким шаблоном відповідати (див. mentorTemplates.js)
//   triggers  — нормалізовані фрази/слова-ознаки цього наміру
//   isMeta    — true, якщо це НЕ питання про зміст уроку (не йде в
//               keyword-пошук по теорії, а обробляється окремим шаблоном)

// Типові скорочення/сленг/одруківки з ТЗ — приводимо до канонічної форми
// ще до токенізації, щоб "шо", "чо", "незнаю" тощо розпізнавались так само,
// як повні форми.
const SLANG_MAP = [
  [/\bшо\b/g, 'що'],
  [/\bчо\b/g, 'чому'],
  [/непон\w*/g, 'не поняла'],
  [/незрозум\w*/g, 'не зрозуміла'],
  [/незна\w*/g, 'не знаю'],
  [/ненаю/g, 'не знаю'],
  [/непрацює/g, 'не працює'],
  [/нєпон\w*/g, 'не поняла'],
  [/фигма/g, 'figma'],
  [/фігма/g, 'figma'],
  [/авто\s*лейаут/g, 'auto layout'],
  [/автолейаут/g, 'auto layout'],
]

// Приводить текст до порівнюваного вигляду: нижній регістр, без розділових
// знаків, без повторів літер ("ааааа" → "аа"), сленг замінено канонічною
// формою. Не чіпає латиницю/цифри (потрібні для термінів типу Figma, CSS).
export function normalizeText(raw) {
  let t = (raw || '').toLowerCase().trim()
  t = t.replace(/[.,!?;:()«»"'\-–—]/g, ' ')
  t = t.replace(/(.)\1{2,}/g, '$1$1') // ааааа -> аа, ооооо -> оо
  for (const [pattern, replacement] of SLANG_MAP) t = t.replace(pattern, replacement)
  t = t.replace(/\s+/g, ' ').trim()
  return t
}

function tokens(text) {
  return (text.match(/[\p{L}\p{N}]+/gu) || []).filter((w) => w.length > 1)
}

// Повністю без слів — лише емодзі/пунктуація/пробіли (крик душі без тексту).
const CRY_EMOJI = /😭|😵|🥲|💀|😩|😫|🙏/
export function isWordless(raw) {
  const t = (raw || '').trim()
  if (!t) return false
  const hasLetters = /[\p{L}]/u.test(t)
  if (hasLetters) {
    const words = normalizeText(t)
    return ['що', 'ааа', 'допоможіть', 'рятуйте', 'капець', 'все', 'help'].includes(words)
  }
  return CRY_EMOJI.test(t) || /^[?!.\s]+$/.test(t)
}

